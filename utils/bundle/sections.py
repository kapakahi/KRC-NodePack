"""The KRC bundle's sections (UNIFIED_BUNDLE_GAMEPLAN.md): one per kind of data.

Each node registers its own section when it registers its routes (so a node that fails
to load just has no section); every Loadout Kit gets one from the kit registry at request
time ("kit_presets/<kit id>"), so NodePack never names a kit.

A section:
  id         its folder in a bundle and its transfer-history key
  label      for logs
  count()    -> how many items it would export (the Export dialog's count)
  export(archive, selection) -> {"counts": {...}, "links": {section id: [item ids]}}
             writes into a SectionArchive. selection: None = everything, or the section's
             subset ({"categories": [...]}, {"banks": [...]}, {"ids": [...]} for presets
             another section links to). "links" = items of other sections this export
             refers to (Prompt Vault -> LoRA / kit presets), for Include linked presets.
  plan(archive, mode, options, stager) -> ImportPlan
             reads the section's folder and decides every write, OUTSIDE any transaction
             (parse, scan, stage thumbnails through the Stager); writes nothing. mode is
             "merge" or "overwrite"; options = {"history": bool}.

  slices     [(table, WHERE clause or None)]: the krc.db rows the section owns; Undo last
             import restores exactly these from the pre-import copy
  stores     [(store, item or None)]: the `changes` entries those rows belong to (item narrows
             a shared store: usage's domain, folder_colors' lineage); caches reload after an undo
  refresh()  optional: drop the section's in-memory caches (after an import or an undo)

An ImportPlan's apply() does only the DB writes and runs inside the import's one
db.write() transaction; after() (optional) runs once the files are in place.
summary = {"added", "updated", "unchanged", "skipped", "reasons": {reason: count}}.
"""
from dataclasses import dataclass
from typing import Callable

KIT_SECTION_PREFIX = "kit_presets/"
# The order sections are listed and written in (kits follow, by id).
CORE_ORDER = ("lora_library", "lora_presets", "model_library", "collections", "prompt_vault",
              "config_switcher_presets", "word_bank")


@dataclass
class Section:
    id: str
    label: str
    count: Callable[[], int]
    export: Callable
    plan: Callable = None
    slices: tuple = ()
    stores: tuple = ()
    refresh: Callable = None


@dataclass
class ImportPlan:
    summary: dict
    apply: Callable[[], dict]
    after: Callable = None
    slices: tuple = None  # optional per-import Undo scope, generated by the section


def plan_summary(added=0, updated=0, unchanged=0, skipped=None):
    """The summary dict. ``skipped`` = {reason: count}."""
    skipped = {reason: count for reason, count in (skipped or {}).items() if count}
    return {"added": added, "updated": updated, "unchanged": unchanged,
            "skipped": sum(skipped.values()), "reasons": skipped}


_SECTIONS = {}
_PACK_SECTIONS = {}  # section id -> (pack id, Section): KRC packs' sections (pack_sections.py)


def register_pack_section(pack_id, section):
    """A KRC pack's section (public API: pack_sections.register_bundle_section)."""
    _PACK_SECTIONS[section.id] = (pack_id, section)
    return section


def _loaded_pack_sections():
    """The pack sections whose pack is allowlisted and loaded, by id."""
    if not _PACK_SECTIONS:
        return []
    try:
        from ..krc_packs import STATUS_OK, krc_pack_status
    except Exception:  # noqa: BLE001
        return []
    out = []
    for section_id in sorted(_PACK_SECTIONS):
        pack_id, section = _PACK_SECTIONS[section_id]
        status = krc_pack_status(pack_id)
        if status and status.get("status") == STATUS_OK:
            out.append(section)
    return out


def register_section(section):
    """Add (or replace) a core section. Idempotent."""
    _SECTIONS[section.id] = section
    return section


def _kit_sections():
    try:
        from ..loadout_kit.kit import all_kits
        from ..loadout_kit.transfer import kit_presets_section
    except Exception:  # noqa: BLE001 - the kit framework didn't load
        return []
    return [kit_presets_section(kit) for _kit_id, kit in sorted(all_kits().items())]


def all_sections():
    """Every section, core ones in CORE_ORDER, then one per kit, then KRC packs' sections."""
    core = [_SECTIONS[section_id] for section_id in CORE_ORDER if section_id in _SECTIONS]
    core += [section for section_id, section in _SECTIONS.items() if section_id not in CORE_ORDER]
    return core + _kit_sections() + _loaded_pack_sections()


def get_section(section_id):
    return next((section for section in all_sections() if section.id == section_id), None)
